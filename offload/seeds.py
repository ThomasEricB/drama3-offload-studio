"""Seeds: the random draws of a take, made repeatable.

Drama 3 samples every frame with noise from the device's global random generator
(fish_omni/tower.py: `exponential_()`), which the Space never seeds: each take, and each
chunk of a long script, draws different numbers, and with them a different delivery (a
clone's pitch alone varies by a std of ~4-5 semitones between draws at the Studio's
defaults). Here every take has a seed (given, or picked at random and reported):

- the engine seeds the generator right after each prompt's prefill (graph capture and the
  prefill itself consume random numbers, so a seed set before it would not hold), so the
  same seed, script, voice and settings make the same take;
- every chunk of a long script starts from the take's seed, so each chunk gets the same
  draws, and a chunk regenerated by an edit is made exactly as it was in the full take;
- a remake (the word check's retries, a chunk remade after a stall, the opening check's
  restarts, an infill's second try, the server's retry of a failed opening) uses a seed
  derived from it (attempt_seed), else it would repeat the same failure. The derivation
  is fixed, so a take made again from its seed takes the same remakes;
- a retake keeps its take's seed unless another one is given.
"""
# (no `from __future__ import annotations`: FastAPI reads the route's body annotation,
# a class local to install_server, at runtime)
import functools
import secrets
import sys

SEED_LIMIT = 2**32  # seeds are 0 .. 4294967295 (exact in JavaScript, and for every backend)
SEED_KEY = "_drama3_seed"  # engine payload: the seed of this generation
TAKE_SEED_KEY = "_drama3_take_seed"  # engine payload: the take's own seed (reported, kept)
ATTEMPT_STEP = 0x9E3779B9  # spreads the remakes' seeds across the range
SERVER_RETRY = 16  # the server's retry of a failed opening (the engine's own attempts stay below)


def attempt_seed(seed: int, attempt: int) -> int:
    """The seed of a take's remake number `attempt` (0 = the take's own seed)."""
    return seed if attempt == 0 else (seed + attempt * ATTEMPT_STEP) % SEED_LIMIT


def seed_rng(seed: int) -> None:
    """Seed the generators the backends sample with: torch (CPU, CUDA, MPS), and MLX on
    its own thread for the MLX backend."""
    import torch

    torch.manual_seed(seed)
    mlx = sys.modules.get("drama3_mlx")
    if mlx is not None and getattr(mlx, "ACTIVE", False):
        mlx.seed(seed)


def checked(seed) -> int | None:
    """A Studio box's value as a seed: None when empty, else an int in range."""
    if seed is None or seed == "":
        return None
    return int(seed) % SEED_LIMIT


# ─── Server ───────────────────────────────────────────────────────────────────


def install_server(server, settings: dict) -> None:
    """`seed` on /api/generate and on the Studio's takes (settings["seed"], the Studio's
    Seed box), the seed on each Take (`take.seed`) and on each of its events."""
    import gradio_ui
    from fastapi import Request
    from fastapi.routing import APIRoute
    from pydantic import Field

    class SeededBody(server.GenerateBody):
        seed: int | None = Field(default=None, ge=0, lt=SEED_LIMIT)

    # The Studio builds its bodies from server.GenerateBody; the route is bound to the
    # class it was declared with, so it is declared again (in its place, ahead of the
    # Studio's mount at /)
    server.GenerateBody = SeededBody
    generate, routes = server.generate, server.app.router.routes
    index, old = next((i, r) for i, r in enumerate(routes)
                      if isinstance(r, APIRoute) and r.path == "/api/generate")

    async def seeded_generate(body: SeededBody, identity=server.Depends(server.identify),
                              request: Request = None):
        return await generate(body, identity, request)

    server.app.add_api_route("/api/generate", seeded_generate, methods=["POST"])
    routes.remove(old)
    routes.insert(index, routes.pop())

    studio_body = gradio_ui.Studio.body

    @functools.wraps(studio_body)
    def body_with_seed(self, *args, **kwargs):
        body = studio_body(self, *args, **kwargs)
        body.seed = settings.get("seed")
        return body

    gradio_ui.Studio.body = body_with_seed

    engine_request = server.engine_request

    @functools.wraps(engine_request)
    def seeded_request(choice, turn_text, history, body):
        payload = engine_request(choice, turn_text, history, body)
        seed = getattr(body, "seed", None)
        if seed is None and getattr(body, "retake_of", None):
            seed = getattr(server.store.take(body.retake_of), "seed", None)
        if seed is None:
            seed = secrets.randbelow(SEED_LIMIT)
        payload[SEED_KEY] = payload[TAKE_SEED_KEY] = seed
        return payload

    server.engine_request = seeded_request

    # The take's events and record are made in server.generate's stream(), whose
    # engine payload holds the seed (found as TimedSilenceGuard finds it; the start
    # event is sent from a helper inside it, a frame further down)
    def take_payload() -> dict | None:
        frame = sys._getframe(2)
        for _ in range(3):
            if frame is None:
                break
            payload = frame.f_locals.get("payload")
            if isinstance(payload, dict) and TAKE_SEED_KEY in payload:
                return payload
            frame = frame.f_back
        return None

    sse = server.sse

    @functools.wraps(sse)
    def seeded_sse(event: dict) -> str:
        payload = take_payload()
        if payload is not None:
            # on every event: a take stopped before its done event still has its seed
            # (the Studio's stage keeps only the latest of a burst of updates)
            event = dict(event, seed=payload[TAKE_SEED_KEY])
            if event.get("type") == "retrying":  # its next attempt must not draw the same numbers
                payload[SEED_KEY] = attempt_seed(payload[TAKE_SEED_KEY], SERVER_RETRY)
        return sse(event)

    server.sse = seeded_sse

    add_take = server.store.add_take

    @functools.wraps(add_take)
    def add_seeded_take(take) -> None:
        payload = take_payload()
        take.seed = payload[TAKE_SEED_KEY] if payload is not None else None
        add_take(take)

    server.store.add_take = add_seeded_take
